"""Small 1.7.10 API-name table, reproducible from an installed Forge SRG resource.
No Minecraft code or assets are included. Input itself never depends on this table.
"""

import argparse
import json
import lzma
import zipfile

from mcbench.paths import ROOT


def descriptor(text):
    primitives = {
        "B": "byte",
        "C": "char",
        "D": "double",
        "F": "float",
        "I": "int",
        "J": "long",
        "S": "short",
        "Z": "boolean",
        "V": "void",
    }

    def one(offset):
        arrays = 0
        while text[offset] == "[":
            arrays += 1
            offset += 1
        if text[offset] == "L":
            end = text.index(";", offset)
            name = text[offset + 1 : end].replace("/", ".")
            offset = end + 1
        else:
            name = primitives[text[offset]]
            offset += 1
        return name + "[]" * arrays, offset

    args = []
    index = 1
    while text[index] != ")":
        name, index = one(index)
        args.append(name)
    result, _ = one(index + 1)
    return result, args


def generate(srg):
    aliases = json.loads((ROOT / "config/legacy1710-aliases.json").read_text())
    classes = {}
    fields = {}
    methods = {}
    for line in srg.splitlines():
        p = line.split()
        if not p:
            continue
        if p[0] == "CL:":
            classes[p[2].replace("/", ".")] = p[1].replace("/", ".")
        elif p[0] == "FD:":
            fields[p[2].replace("/", ".")] = p[1].split("/")[-1]
        elif p[0] == "MD:":
            owner, name = p[3].rsplit("/", 1)
            ret, args = descriptor(p[4])
            key = owner.replace("/", ".") + "." + name + "." + str(len(args))
            methods[key] = (p[1].split("/")[-1], ret, args)
    props = {}
    for owner, value in aliases.items():
        actual = classes[owner]
        props["class." + owner] = actual
        props["reverse." + actual] = owner
        for logical, srgname in value.get("fields", {}).items():
            props["field." + owner + "." + logical] = fields[owner + "." + srgname]
        for logical, srgname in value.get("methods", {}).items():
            arity = logical.rsplit(".", 1)[1]
            actual, ret, args = methods[owner + "." + srgname + "." + arity]
            props["method." + owner + "." + logical] = actual
            props["signature." + owner + "." + logical] = actual + "|" + ret + "|" + ",".join(args)
    return props


def prepare():
    props = {}
    for line in (ROOT / "config/minecraft1710-bindings.properties").read_text().splitlines():
        if line and not line.startswith("#"):
            key, value = line.split("=", 1)
            props[key] = value
    return props


if __name__ == "__main__":
    p = argparse.ArgumentParser()
    p.add_argument("--forge-jar", required=True)
    a = p.parse_args()
    with zipfile.ZipFile(a.forge_jar) as z:
        props = generate(lzma.decompress(z.read("deobfuscation_data-1.7.10.lzma")).decode())
    (ROOT / "config/minecraft1710-bindings.properties").write_text(
        "# Minimal API compatibility names only; generated by scripts/legacy_bindings.py\n"
        + "\n".join(k + "=" + v for k, v in sorted(props.items()))
        + "\n"
    )
    print("Generated", len(props), "names")
